class EmotionConverter:
    """表情转义转换器"""

    @staticmethod
    def convert_emoji_to_qq(text: str) -> str:
        """将文本中的 emoji 转换为 QQ 表情代码"""
        result = text
        for emoji, qq_emotion in EMOTION_MAP.items():
            result = result.replace(emoji, qq_emotion)
        return result

    @staticmethod
    def convert_qq_to_emoji(text: str) -> str:
        """将 QQ 表情代码转换为 emoji（可选）"""
        result = text
        emotion_reverse_map = {v: k for k, v in EMOTION_MAP.items()}
        for qq_emotion, emoji in emotion_reverse_map.items():
            result = result.replace(qq_emotion, emoji)
        return result
